package gen

// RenderGeneratedFile renders the snapshot.gen.go payload from the
// vendored artifacts. The render is DETERMINISTIC: identical inputs
// produce byte-identical output (stable node ordering, fixed template,
// explicit rendering of every contract dimension), and the offline test
// re-renders and byte-compares against the checked-in file. The generator
// (providerschema/generate.go) imports THIS package only — it bootstraps
// from vendored source + manifest even when snapshot.gen.go is absent.

import (
	"bytes"
	"fmt"
	"strings"
)

// RenderGeneratedFile parses the vendored source and renders the complete
// snapshot.gen.go payload.
func RenderGeneratedFile() ([]byte, error) {
	nodes, orders, err := ParseVendoredSource()
	if err != nil {
		return nil, err
	}
	m, err := LoadManifest()
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by generate.go from the vendored provider artifacts\n")
	b.WriteString("// (providerschema/source/*.proto + source/manifest.json). DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Immutable upstream inputs (see source/manifest.json for full provenance,\n")
	b.WriteString("// fetch date, and license):\n")
	b.WriteString("//\n")
	for _, f := range m.Files {
		fmt.Fprintf(&b, "//\t%s @ %s (%s)\n", f.Path, f.UpstreamCommitSHA, f.UpstreamCommitDate)
	}
	b.WriteString("//\n")
	b.WriteString("// Deterministic regeneration: ./generate.sh (byte-identical across runs;\n")
	b.WriteString("// TestSnapshotGeneratedExact enforces it offline).\n")
	b.WriteString("package providerschema\n\n")
	b.WriteString("// schemaNodes is the complete machine-derived node set. Every node\n")
	b.WriteString("// carries the contract dimensions the adapter grammar needs: oneof\n")
	b.WriteString("// membership (arms are `data`-oneof members), repeated cardinality,\n")
	b.WriteString("// proto3 optional presence, and google.api.field_behavior.\n")
	b.WriteString("var schemaNodes = []SchemaNode{\n")
	for _, n := range nodes {
		surf := strings.Join(n.Surfaces, `", "`)
		fb := n.FieldBehavior
		if fb == "" {
			fb = BehaviorUnspecified
		}
		fmt.Fprintf(&b, "\t{ID: %q, Member: %q, Kind: %q, Surfaces: []string{\"%s\"}, Oneof: %q, Repeated: %v, Optional: %v, FieldBehavior: %q},\n",
			n.ID, n.Member, n.Kind, surf, n.Oneof, n.Repeated, n.Optional, string(fb))
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, "\n// schedulingArtifactOrder / mediaResolutionLevelArtifactOrder (provider enum order).\n")
	fmt.Fprintf(&b, "var schedulingArtifactOrder = []string{\"%s\"}\n", strings.Join(orders.Scheduling, `", "`))
	fmt.Fprintf(&b, "var mediaResolutionLevelArtifactOrder = []string{\"%s\"}\n", strings.Join(orders.MediaResolutionLevel, `", "`))
	return b.Bytes(), nil
}
